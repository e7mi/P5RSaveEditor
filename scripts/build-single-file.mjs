// Concatenate web/js modules into web/bundle.js so index.html also works on
// file://, where module imports are blocked. Run after editing web/js or web/data.js:
//   node scripts/build-single-file.mjs

import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ORDER = [
  'data.js',
  'js/util.js',
  'js/aes.js',
  'js/input.js',
  'js/calendar.js',
  'js/tables.js',
  'js/savefile.js',
  'js/gamedata.js',
  'js/app.js',
];

let out = '// Generated by scripts/build-single-file.mjs. Do not edit.\n';
for (const name of ORDER) {
  let src = readFileSync(join(root, 'web', name), 'utf8');
  src = src
    .replace(/import\s+[\s\S]*?from\s+['"][^'"]+['"]\s*;/g, '')
    .replace(/^export\s*\{[^}]*\}\s*;?/m, '')
    .replace(/^export\s+(?=(const|let|var|function|class|async|default))/gm, '');
  out += `\n// ---- ${name} ----\n` + src;
}
writeFileSync(join(root, 'web', 'bundle.js'), out, 'utf8');
console.log(`web/bundle.js written (${out.length} bytes)`);
